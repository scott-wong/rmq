#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"
source_baseline

sbom="${1:?usage: enrich-sbom.sh SBOM.json}"
[ -f "$sbom" ] || die "SBOM not found: $sbom"
require_command python3

RMQ_VERSION="$(tr -d ' \n' < "$ROOT_DIR/VERSION")"
[ -n "$RMQ_VERSION" ] || die "VERSION is empty"
IMAGE_VERSION="${IMAGE_VERSION:-${RMQ_VERSION}-openeuler}"

RMQ_VERSION="$RMQ_VERSION" \
IMAGE_VERSION="$IMAGE_VERSION" \
RABBITMQ_VERSION="$RABBITMQ_VERSION" \
RABBITMQ_TARBALL_URL="$RABBITMQ_TARBALL_URL" \
RABBITMQ_TARBALL_SHA256="$RABBITMQ_TARBALL_SHA256" \
RABBITMQADMIN_VERSION="$RABBITMQADMIN_VERSION" \
RABBITMQADMIN_URL="$RABBITMQADMIN_URL" \
RABBITMQADMIN_SHA256="$RABBITMQADMIN_SHA256" \
OTP_VERSION="$OTP_VERSION" \
OTP_URL="$OTP_URL" \
OTP_SHA256="$OTP_SHA256" \
OPENSSL_VERSION="$OPENSSL_VERSION" \
OPENSSL_URL="$OPENSSL_URL" \
OPENSSL_SHA256="$OPENSSL_SHA256" \
GOSU_VERSION="$GOSU_VERSION" \
GOSU_SOURCE_URL="$GOSU_SOURCE_URL" \
GOSU_SOURCE_SHA256="$GOSU_SOURCE_SHA256" \
    python3 "$SCRIPT_DIR/enrich-sbom.py" "$sbom"
